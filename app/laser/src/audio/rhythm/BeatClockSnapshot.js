import {
  BEAT_CLOCK_SCHEMA_VERSION,
  BPM_BEAT_PHASE_FOUNDATION_VERSION,
  RHYTHM_ROBUSTNESS_TRANSITION_VERSION,
  RHYTHM_HARMONIC_STABILITY_VERSION,
  RHYTHM_GRID_FOUNDATION_VERSION,
} from './RhythmConfig.js';

const finite = (value, fallback = 0) => Number.isFinite(Number(value)) ? Number(value) : fallback;
const clamp01 = (value) => Math.max(0, Math.min(1, finite(value)));

const deepFreeze = (value) => {
  if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value;
  for (const child of Object.values(value)) deepFreeze(child);
  return Object.freeze(value);
};

export const createBeatClockSnapshot = ({
  timestamp = 0,
  mode = 'auto',
  candidateAnalysis = {},
  novelty = {},
  tempo = {},
  beat = {},
  tap = {},
} = {}) => deepFreeze({
  schemaVersion: BEAT_CLOCK_SCHEMA_VERSION,
  foundationVersion: BPM_BEAT_PHASE_FOUNDATION_VERSION,
  rhythmGridVersion: RHYTHM_GRID_FOUNDATION_VERSION,
  rhythmRobustnessVersion: RHYTHM_ROBUSTNESS_TRANSITION_VERSION,
  rhythmHarmonicStabilityVersion: RHYTHM_HARMONIC_STABILITY_VERSION,
  timestamp: Math.max(0, finite(timestamp)),
  mode: ['auto', 'tap-assist', 'manual'].includes(mode) ? mode : 'auto',
  candidate: {
    detected: Boolean(candidateAnalysis.candidate),
    timestamp: Math.max(0, finite(candidateAnalysis.candidate?.timestamp || candidateAnalysis.lastCandidateTimestamp)),
    strength: clamp01(candidateAnalysis.strength),
    confidence: clamp01(candidateAnalysis.confidence),
    lowEndContribution: clamp01(candidateAnalysis.lowEndContribution),
    broadbandContribution: clamp01(candidateAnalysis.broadbandContribution),
    spectralContribution: clamp01(candidateAnalysis.spectralContribution),
    reasonFlags: [...(candidateAnalysis.reasonFlags || [])].map(String),
  },
  novelty: {
    lowEndNovelty: clamp01(novelty.lowEndNovelty),
    broadbandNovelty: clamp01(novelty.broadbandNovelty),
    spectralNovelty: clamp01(novelty.spectralNovelty),
    highFrequencyNovelty: clamp01(novelty.highFrequencyNovelty),
    combinedNovelty: clamp01(novelty.combinedNovelty),
    adaptiveBaseline: clamp01(novelty.adaptiveBaseline),
    adaptiveThreshold: clamp01(novelty.adaptiveThreshold),
  },
  tempo: {
    state: String(tempo.state || 'searching'),
    bpm: Math.max(0, finite(tempo.bpm)),
    confidence: clamp01(tempo.confidence),
    stability: clamp01(tempo.stability),
    lockAgeMs: Math.max(0, finite(tempo.lockAgeMs)),
    candidateCount: Math.max(0, Math.floor(finite(tempo.candidateCount))),
    topCandidates: [...(tempo.topCandidates || [])].slice(0, 5).map((entry) => ({
      bpm: Math.max(0, finite(entry.bpm)),
      score: clamp01(entry.score),
      confidence: clamp01(entry.confidence),
      supportCount: Math.max(0, Math.floor(finite(entry.supportCount))),
      harmonicRelation: String(entry.harmonicRelation || 'none'),
      periodicityScore: clamp01(entry.periodicityScore),
      phaseFitScore: clamp01(entry.phaseFitScore),
      multiBandAgreement: clamp01(entry.multiBandAgreement),
      continuityScore: clamp01(entry.continuityScore),
      harmonicScore: clamp01(entry.harmonicScore),
      supportDurationMs: Math.max(0, finite(entry.supportDurationMs)),
    })),
    reason: String(tempo.reason || ''),
    lastTempoChangeAt: Math.max(0, finite(tempo.lastTempoChangeAt)),
    lastTempoChangeReason: tempo.lastTempoChangeReason ? String(tempo.lastTempoChangeReason) : null,
    rhythmContextResetReason: tempo.rhythmContextResetReason ? String(tempo.rhythmContextResetReason) : null,
    periodicityScore: clamp01(tempo.periodicityScore),
    phaseFitScore: clamp01(tempo.phaseFitScore),
    multiBandAgreement: clamp01(tempo.multiBandAgreement),
    continuityScore: clamp01(tempo.continuityScore),
    onGridScore: clamp01(tempo.onGridScore),
    offGridScore: clamp01(tempo.offGridScore),
    lastTempoChange: tempo.lastTempoChange ? { ...tempo.lastTempoChange } : null,
    lockMaturity: clamp01(tempo.lockMaturity),
    lockMaturityLabel: String(tempo.lockMaturityLabel || 'immature'),
    halfTimeCandidate: tempo.halfTimeCandidate ? { ...tempo.halfTimeCandidate } : null,
    fullTimeCandidate: tempo.fullTimeCandidate ? { ...tempo.fullTimeCandidate } : null,
    fullTimeEvidence: clamp01(tempo.fullTimeEvidence),
    harmonicScoreDelta: finite(tempo.harmonicScoreDelta),
    harmonicConfidenceDelta: finite(tempo.harmonicConfidenceDelta),
    harmonicRelation: String(tempo.harmonicRelation || 'none'),
    baseBpm: Math.max(0, finite(tempo.baseBpm)),
    doubleBpm: Math.max(0, finite(tempo.doubleBpm)),
    intermediateBeatSupport: clamp01(tempo.intermediateBeatSupport),
    intermediateEventQuality: clamp01(tempo.intermediateEventQuality),
    baseTempoEvidence: clamp01(tempo.baseTempoEvidence),
    intermediateSupportConsistency: clamp01(tempo.intermediateSupportConsistency),
    intermediateMultiBandAgreement: clamp01(tempo.intermediateMultiBandAgreement),
    intermediateSupportDurationMs: Math.max(0, finite(tempo.intermediateSupportDurationMs)),
    intermediateOnsetRegularity: clamp01(tempo.intermediateOnsetRegularity),
    dancePriorContribution: clamp01(tempo.dancePriorContribution),
    finalHarmonicDecision: String(tempo.finalHarmonicDecision || 'none'),
    harmonicRelockPersistenceMs: Math.max(0, finite(tempo.harmonicRelockPersistenceMs)),
    fullTimeSupportHistory: clamp01(tempo.fullTimeSupportHistory),
    halfTimeTakeoverEvidence: clamp01(tempo.halfTimeTakeoverEvidence),
    halfTimeTakeoverReason: String(tempo.halfTimeTakeoverReason || 'none'),
    harmonicLockMaturity: clamp01(tempo.harmonicLockMaturity),
    harmonicAmbiguity: clamp01(tempo.harmonicAmbiguity),
    tempoCenterBpm: Math.max(0, finite(tempo.tempoCenterBpm)),
    tempoClusterSpreadBpm: Math.max(0, finite(tempo.tempoClusterSpreadBpm)),
    tempoRefinementSlewBpmPerSecond: Math.max(0, finite(tempo.tempoRefinementSlewBpmPerSecond)),
    instantaneousBestBpm: Math.max(0, finite(tempo.topCandidates?.[0]?.bpm)),
    clusterDeltaBpm: finite((tempo.topCandidates?.[0]?.bpm || tempo.bpm)
      - (tempo.tempoCenterBpm || tempo.bpm)),
    transitionPending: /tempo-change-(pending|observing)/.test(String(tempo.reason || '')),
    harmonicRelockPending: /harmonic-(relock-pending|change-observing)/.test(String(tempo.reason || '')),
    lockFreshness: clamp01(tempo.lockFreshness),
    lastStrongAnchorAgeMs: tempo.lastStrongAnchorAgeMs === null
      ? null : Math.max(0, finite(tempo.lastStrongAnchorAgeMs)),
    lastAnyAnchorAgeMs: tempo.lastAnyAnchorAgeMs === null
      ? null : Math.max(0, finite(tempo.lastAnyAnchorAgeMs)),
    recentAnchorCount: Math.max(0, Math.floor(finite(tempo.recentAnchorCount))),
    recentGridSupport: clamp01(tempo.recentGridSupport),
    recentTempoAgreement: clamp01(tempo.recentTempoAgreement),
    rhythmicContinuity: clamp01(tempo.rhythmicContinuity),
    staleLockScore: clamp01(tempo.staleLockScore),
    transitionState: String(tempo.transitionState || 'transition-search'),
    transitionOldTempo: Math.max(0, finite(tempo.transitionOldTempo)),
    transitionCandidateTempo: Math.max(0, finite(tempo.transitionCandidateTempo)),
    staleDurationMs: Math.max(0, finite(tempo.staleDurationMs)),
    reacquireDurationMs: Math.max(0, finite(tempo.reacquireDurationMs)),
    acquisitionConfidence: clamp01(tempo.acquisitionConfidence),
    acquisitionMaturity: clamp01(tempo.acquisitionMaturity),
    lockQuality: clamp01(tempo.lockQuality),
    periodicityConfidence: clamp01(tempo.periodicityConfidence),
    acquisitionAnchorSupport: clamp01(tempo.acquisitionAnchorSupport),
    acquisitionEvidenceAgeMs: Math.max(0, finite(tempo.acquisitionEvidenceAgeMs)),
    acquisitionReason: String(tempo.acquisitionReason || 'none'),
  },
  beat: {
    state: String(beat.state || 'searching'),
    phase: clamp01(beat.phase),
    periodMs: Math.max(0, finite(beat.periodMs)),
    lastBeatTime: Math.max(0, finite(beat.lastBeatTime)),
    predictedNextBeatTime: Math.max(0, finite(beat.predictedNextBeatTime)),
    timeToNextBeatMs: Math.max(0, finite(beat.timeToNextBeatMs)),
    beatIndexSinceLock: Math.max(0, Math.floor(finite(beat.beatIndexSinceLock))),
    provisionalGridPosition: Math.max(0, Math.floor(finite(beat.provisionalGridPosition))) % 4,
    gridConfidence: clamp01(beat.gridConfidence ?? beat.phaseConfidence),
    gridStability: clamp01(beat.gridStability),
    supportScore: clamp01(beat.supportScore),
    missingBeatTolerance: Math.max(0, Math.floor(finite(beat.missingBeatTolerance))),
    nearestCandidateDistanceMs: beat.nearestCandidateDistanceMs === null
      ? null : finite(beat.nearestCandidateDistanceMs),
    candidateAcceptedForCorrection: Boolean(beat.candidateAcceptedForCorrection),
    candidateEvaluated: Boolean(beat.candidateEvaluated),
    candidateClassification: String(beat.candidateClassification || 'none'),
    candidateWeight: clamp01(beat.candidateWeight),
    audioAnchorRate: clamp01(beat.audioAnchorRate),
    audioAnchorCount: Math.max(0, Math.floor(finite(beat.audioAnchorCount))),
    audioAnchorCorrections: Math.max(0, Math.floor(finite(beat.audioAnchorCorrections))),
    audioAnchorConfirmations: Math.max(0, Math.floor(finite(beat.audioAnchorConfirmations))),
    audioAnchorCandidates: Math.max(0, Math.floor(finite(beat.audioAnchorCandidates))),
    offGridCandidateCount: Math.max(0, Math.floor(finite(beat.offGridCandidateCount))),
    anchorClustering: {
      clusterSize: Math.max(0, Math.floor(finite(beat.clusterCandidateCount))),
      clusterDurationMs: Math.max(0, finite(beat.clusterDurationMs)),
      clusterStrength: clamp01(beat.clusterStrength),
      representativeOffsetMs: beat.representativeCandidateOffsetMs === null
        ? null : finite(beat.representativeCandidateOffsetMs),
      accepted: Boolean(beat.anchorAccepted),
      rejectReason: String(beat.anchorRejectReason || 'none'),
      offsetConsistency: clamp01(beat.anchorOffsetConsistency),
      clusterCount: Math.max(0, Math.floor(finite(beat.anchorClusterCount))),
      rejectedDuplicateOnsets: Math.max(0, Math.floor(finite(beat.rejectedDuplicateOnsets))),
      acceptedClusterAnchors: Math.max(0, Math.floor(finite(beat.acceptedClusterAnchors))),
    },
    phaseConfidence: clamp01(beat.phaseConfidence),
    correctionMs: finite(beat.correctionMs),
    isPredictedBeat: Boolean(beat.isPredictedBeat),
    isObservedBeat: Boolean(beat.isObservedBeat),
    event: beat.event ? {
      timestamp: Math.max(0, finite(beat.event.timestamp)),
      predictedTimestamp: Math.max(0, finite(beat.event.predictedTimestamp)),
      observedCandidateTimestamp: beat.event.observedCandidateTimestamp === null
        ? null : Math.max(0, finite(beat.event.observedCandidateTimestamp)),
      source: beat.event.source === 'observed-corrected' ? 'observed-corrected' : 'predicted',
      strength: clamp01(beat.event.strength),
      confidence: clamp01(beat.event.confidence),
      bpm: Math.max(0, finite(beat.event.bpm)),
      phaseErrorMs: finite(beat.event.phaseErrorMs),
    } : null,
  },
  tap: {
    tapCount: Math.max(0, Math.floor(finite(tap.tapCount))),
    bpm: Math.max(0, finite(tap.bpm)),
    confidence: clamp01(tap.confidence),
    ready: Boolean(tap.ready),
  },
});
